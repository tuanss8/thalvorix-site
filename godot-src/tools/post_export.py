#!/usr/bin/env python3
"""Run after every web export:  python3 godot-src/tools/post_export.py godot

Writes godot/sw.js, a service worker that keeps this exact build (engine, game
data, shell) in Cache Storage so repeat visits skip the download. The cache name
is a hash of the exported files, so every new export becomes a new cache and the
old one is deleted when the new worker activates (cache busting)."""
import hashlib, json, os, sys

out = sys.argv[1] if len(sys.argv) > 1 else "godot"
FILES = ["index.html", "index.js", "index.wasm", "index.pck", "index.audio.worklet.js",
         "index.audio.position.worklet.js", "index.png", "index.icon.png", "index.apple-touch-icon.png"]
# duel-arena/ shares the engine (index.wasm + audio worklets) from /godot/ —
# the GitHub web UI refuses files over 25 MB, so the 39.5 MB wasm cannot live
# here. Only the files that actually exist in this folder go into the cache.
if out.rstrip("/").endswith("duel-arena"):
    FILES = [f for f in FILES if f not in ("index.wasm", "index.audio.worklet.js",
                                          "index.audio.position.worklet.js")]
FILES = [f for f in FILES if os.path.isfile(os.path.join(out, f))]
h = hashlib.sha256()
sizes = {}
for f in FILES:
    b = open(os.path.join(out, f), "rb").read()
    h.update(f.encode()); h.update(b)
    sizes[f] = len(b)
ver = h.hexdigest()[:12]

SW = r"""/* THALVORIX Duel Arena 3D - offline cache for repeat visits (generated by tools/post_export.py). */
const VERSION = 'thx-godot-%(ver)s';
const SIZES = %(sizes)s;  // decoded byte size of every cached file of this build
const keyOf = (url) => {
  const u = new URL(url);
  if (!u.pathname.startsWith(self.registration.scope.replace(location.origin, ''))) return null;
  let name = u.pathname.split('/').pop();
  if (name === '') name = 'index.html';
  return name in SIZES ? name : null;
};
// Fetch one file of this build. Tries the HTTP cache first (the page just
// downloaded it), and re-downloads if the size does not match this build.
async function fetchExact(name) {
  for (const mode of ['default', 'reload']) {
    try {
      const r = await fetch(new Request(name, {cache: mode}));
      if (!r.ok) continue;
      const buf = await r.arrayBuffer();
      if (buf.byteLength !== SIZES[name]) continue;
      const headers = new Headers();
      const ct = r.headers.get('content-type');
      if (ct) headers.set('content-type', ct);
      headers.set('content-length', String(buf.byteLength));
      return new Response(buf, {status: 200, headers});
    } catch (e) { /* try next mode */ }
  }
  return null;
}
self.addEventListener('install', (ev) => {
  ev.waitUntil((async () => {
    const c = await caches.open(VERSION);
    for (const name of Object.keys(SIZES)) {   // one at a time: low memory
      if (await c.match(name)) continue;
      const r = await fetchExact(name);
      if (r) await c.put(name, r);
    }
    await self.skipWaiting();
  })());
});
self.addEventListener('activate', (ev) => {
  ev.waitUntil((async () => {
    for (const k of await caches.keys()) if (k.startsWith('thx-godot-') && k !== VERSION) await caches.delete(k);
    await self.clients.claim();
  })());
});
self.addEventListener('fetch', (ev) => {
  if (ev.request.method !== 'GET') return;
  const name = keyOf(ev.request.url);
  if (!name) return;
  ev.respondWith((async () => {
    const c = await caches.open(VERSION);
    const hit = await c.match(name);
    if (hit) return hit;
    const r = await fetchExact(name);
    if (r) { c.put(name, r.clone()).catch(() => {}); return r; }
    return fetch(ev.request);
  })());
});
""" % {"ver": ver, "sizes": json.dumps(sizes)}
open(os.path.join(out, "sw.js"), "w").write(SW)
print("sw.js", ver, sizes)
